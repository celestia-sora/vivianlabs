-- Phase 2 Memory v2 (additive only). Applies after
-- 20260829000000_vivian_memory.sql + 20260901000000_memory_engagement.sql.
--
-- Rollback: every statement here is additive (ADD COLUMN IF NOT EXISTS,
-- new table). To roll back, drop the columns / table below; no existing
-- column or row is modified destructively. Existing `importance` smallint
-- 1..5 is kept as the canonical legacy column; `importance_01` is the
-- 0..1 projection used by Phase 2 retrieval (see mapping in
-- lib/memory-v2.ts: importanceTo01 / importanceToLegacy).
--
-- pgvector is intentionally NOT enabled in this migration. Prod was
-- verified read-only: extensions present are pg_stat_statements, pgcrypto,
-- plpgsql, supabase_vault, uuid-ossp (no pgvector). The `embedding`
-- column is therefore an inert `double precision[]` placeholder carrying
-- the configured dimension (MEMORY_EMBEDDING_DIM, default 768) until the
-- embedding provider eval lands (see docs/memory-embeddings.md) and the
-- extension + real `vector` type are enabled in a follow-up migration.
-- Retrieval ships keyword+recency only until then.
--
-- NOTE (deviation from plan §8.1 sketch): `superseded_by` is `bigint`
-- referencing memories(id), not `uuid` — memories.id is
-- `bigint generated by default as identity`. `created_at` already exists
-- from the original 20260829000000 migration, so it is not re-added.
-- RLS stays enabled with no public policies (service-role only).

alter table public.memories
  add column if not exists type text not null default 'fact',
  add column if not exists importance_01 real check (importance_01 between 0 and 1),
  add column if not exists last_accessed_at timestamptz,
  add column if not exists access_count integer not null default 0,
  add column if not exists source_message_ids text[] not null default '{}',
  add column if not exists superseded_by bigint references public.memories(id) on delete set null,
  add column if not exists embedding double precision[],
  add column if not exists embedding_model text;

-- Backfill 0..1 from the canonical legacy 1..5 column (1->0, 3->0.5, 5->1).
update public.memories set importance_01 = (importance::real - 1) / 4 where importance_01 is null;

-- Keep legacy + v2 columns in sync for writes that only set one side.
create or replace function public.vivian_memory_sync_importance() returns trigger as $$
begin
  if new.importance_01 is null then
    new.importance_01 := (new.importance::real - 1) / 4;
  elsif tg_op = 'insert' and new.importance is null then
    new.importance := least(5, greatest(1, round(new.importance_01 * 4 + 1)::smallint));
  end if;
  return new;
end;
$$ language plpgsql;

drop trigger if exists memories_sync_importance on public.memories;
create trigger memories_sync_importance
  before insert or update of importance, importance_01 on public.memories
  for each row execute function public.vivian_memory_sync_importance();

create index if not exists memories_user_superseded_idx on public.memories(user_key, superseded_by) where superseded_by is null;
create index if not exists memories_user_type_idx on public.memories(user_key, type);

create table if not exists public.memory_consolidation_runs (
  id uuid primary key default gen_random_uuid(),
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  status text not null default 'running' check (status in ('running', 'done', 'failed')),
  stats jsonb not null default '{}'::jsonb
);

create index if not exists memory_consolidation_runs_running_idx
  on public.memory_consolidation_runs(started_at desc) where status = 'running';

alter table public.memory_consolidation_runs enable row level security;
